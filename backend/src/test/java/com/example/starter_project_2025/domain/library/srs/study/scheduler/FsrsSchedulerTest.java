package com.example.starter_project_2025.domain.library.srs.study.scheduler;

import com.example.starter_project_2025.domain.library.srs.srs_progress.AnkiSrsProgress;
import org.junit.jupiter.api.Test;

import java.time.LocalDateTime;
import java.time.temporal.ChronoUnit;

import static org.junit.jupiter.api.Assertions.assertEquals;

/**
 * Pins {@link FsrsScheduler} to reference values produced by the canonical
 * implementation py-fsrs v4.1.2 (FSRS-5, fuzzing disabled, default 19 weights,
 * default steps 1m/10m & 10m, desired retention 0.9).
 *
 * <p>The expected numbers below were generated by running py-fsrs directly; if
 * the port ever drifts from the reference these tests fail.
 */
class FsrsSchedulerTest {

    private static final double EPS = 1e-6;

    private final FsrsScheduler scheduler = new FsrsScheduler();
    private final LocalDateTime now = LocalDateTime.of(2026, 1, 1, 12, 0, 0);

    private SchedulingConfig defaultConfig() {
        return new SchedulingConfig(); // FSRS-5 defaults (params null ⇒ built-in weights)
    }

    private AnkiSrsProgress newCard() {
        AnkiSrsProgress p = new AnkiSrsProgress();
        p.setState("NEW");
        p.setLearningStepIndex(0);
        p.setReviewCount(0);
        p.setLapses(0);
        return p;
    }

    private AnkiSrsProgress reviewCard(double stability, double difficulty, LocalDateTime lastReviewedAt) {
        AnkiSrsProgress p = new AnkiSrsProgress();
        p.setState("REVIEW");
        p.setStability(stability);
        p.setDifficulty(difficulty);
        p.setLearningStepIndex(0);
        p.setReviewCount(5);
        p.setLapses(0);
        p.setLastReviewedAt(lastReviewedAt);
        p.setFirstLearnedAt(lastReviewedAt);
        return p;
    }

    private long secondsToDue(AnkiSrsProgress p) {
        return ChronoUnit.SECONDS.between(now, p.getNextReviewAt());
    }

    /* ── New card, first review for each rating ── */

    @Test
    void newCard_again() {
        AnkiSrsProgress p = newCard();
        scheduler.review(p, Rating.AGAIN, defaultConfig(), now);

        assertEquals("LEARNING", p.getState());
        assertEquals(0, p.getLearningStepIndex());
        assertEquals(0.40255, p.getStability(), EPS);
        assertEquals(7.1949000000, p.getDifficulty(), EPS);
        assertEquals(60, secondsToDue(p));        // 1m
        assertEquals(0, p.getIntervalDays());
        assertEquals("FSRS", p.getAlgorithmType());
    }

    @Test
    void newCard_hard() {
        AnkiSrsProgress p = newCard();
        scheduler.review(p, Rating.HARD, defaultConfig(), now);

        assertEquals("LEARNING", p.getState());
        assertEquals(0, p.getLearningStepIndex());
        assertEquals(1.18385, p.getStability(), EPS);
        assertEquals(6.4883052685, p.getDifficulty(), EPS);
        assertEquals(330, secondsToDue(p));       // (1m + 10m) / 2 = 5.5m
    }

    @Test
    void newCard_good() {
        AnkiSrsProgress p = newCard();
        scheduler.review(p, Rating.GOOD, defaultConfig(), now);

        assertEquals("LEARNING", p.getState());
        assertEquals(1, p.getLearningStepIndex());
        assertEquals(3.173, p.getStability(), EPS);
        assertEquals(5.2824344223, p.getDifficulty(), EPS);
        assertEquals(600, secondsToDue(p));       // 10m
    }

    @Test
    void newCard_easy() {
        AnkiSrsProgress p = newCard();
        scheduler.review(p, Rating.EASY, defaultConfig(), now);

        assertEquals("REVIEW", p.getState());
        assertEquals(15.69105, p.getStability(), EPS);
        assertEquals(3.2245015894, p.getDifficulty(), EPS);
        assertEquals(16, p.getIntervalDays());
        assertEquals(now.plusDays(16), p.getNextReviewAt());
        assertEquals(16, p.getScheduledDays());
    }

    /* ── Review card, S=10 D=5, last reviewed 10 days ago (R = 0.9) ── */

    @Test
    void reviewCard_again_lapsesAndRelearns() {
        AnkiSrsProgress p = reviewCard(10.0, 5.0, now.minusDays(10));
        scheduler.review(p, Rating.AGAIN, defaultConfig(), now);

        assertEquals("RELEARNING", p.getState());
        assertEquals(2.1076962577, p.getStability(), EPS);
        assertEquals(6.6070351073, p.getDifficulty(), EPS);
        assertEquals(600, secondsToDue(p));       // relearning step 10m
        assertEquals(1, p.getLapses());
        assertEquals(0.9, p.getRetrievability(), 1e-6);
        assertEquals(10, p.getElapsedDays());
    }

    @Test
    void reviewCard_hard() {
        AnkiSrsProgress p = reviewCard(10.0, 5.0, now.minusDays(10));
        scheduler.review(p, Rating.HARD, defaultConfig(), now);

        assertEquals("REVIEW", p.getState());
        assertEquals(15.3139121143, p.getStability(), EPS);
        assertEquals(5.7994339073, p.getDifficulty(), EPS);
        assertEquals(15, p.getIntervalDays());
        assertEquals(0, p.getLapses());
    }

    @Test
    void reviewCard_good() {
        AnkiSrsProgress p = reviewCard(10.0, 5.0, now.minusDays(10));
        scheduler.review(p, Rating.GOOD, defaultConfig(), now);

        assertEquals("REVIEW", p.getState());
        assertEquals(32.9542639925, p.getStability(), EPS);
        assertEquals(4.9918327073, p.getDifficulty(), EPS);
        assertEquals(33, p.getIntervalDays());
    }

    @Test
    void reviewCard_easy() {
        AnkiSrsProgress p = reviewCard(10.0, 5.0, now.minusDays(10));
        scheduler.review(p, Rating.EASY, defaultConfig(), now);

        assertEquals("REVIEW", p.getState());
        assertEquals(78.6286584846, p.getStability(), EPS);
        assertEquals(4.1842315073, p.getDifficulty(), EPS);
        assertEquals(79, p.getIntervalDays());
    }

    /* ── Same-day re-review (elapsed = 0) uses short-term stability ── */

    @Test
    void reviewCard_sameDay_again() {
        AnkiSrsProgress p = reviewCard(10.0, 5.0, now);
        scheduler.review(p, Rating.AGAIN, defaultConfig(), now);

        assertEquals("RELEARNING", p.getState());
        assertEquals(5.0102852419, p.getStability(), EPS); // short-term, not forget-stability
        assertEquals(600, secondsToDue(p));
    }

    @Test
    void reviewCard_sameDay_good() {
        AnkiSrsProgress p = reviewCard(10.0, 5.0, now);
        scheduler.review(p, Rating.GOOD, defaultConfig(), now);

        assertEquals("REVIEW", p.getState());
        assertEquals(14.0777121474, p.getStability(), EPS);
        assertEquals(14, p.getIntervalDays());
    }

    @Test
    void reviewCard_sameDay_easy() {
        AnkiSrsProgress p = reviewCard(10.0, 5.0, now);
        scheduler.review(p, Rating.EASY, defaultConfig(), now);

        assertEquals(23.5975489360, p.getStability(), EPS);
        assertEquals(24, p.getIntervalDays());
    }

    /* ── Multi-step learning progression: NEW → Good → (10m later) Good ── */

    @Test
    void learningProgression_twoGoodsGraduate() {
        SchedulingConfig config = defaultConfig();
        AnkiSrsProgress p = newCard();

        scheduler.review(p, Rating.GOOD, config, now);
        assertEquals("LEARNING", p.getState());
        assertEquals(1, p.getLearningStepIndex());
        assertEquals(3.173, p.getStability(), EPS);

        LocalDateTime tenMinLater = now.plusMinutes(10);
        scheduler.review(p, Rating.GOOD, config, tenMinLater);

        assertEquals("REVIEW", p.getState());
        assertEquals(4.4668580644, p.getStability(), EPS);
        assertEquals(5.2729679313, p.getDifficulty(), EPS);
        assertEquals(4, p.getIntervalDays());
    }

    /* ── Preview must match what review() would actually do ── */

    @Test
    void preview_matchesReviewIntervals() {
        SchedulingConfig config = defaultConfig();
        PreviewResult preview = scheduler.preview(reviewCard(10.0, 5.0, now.minusDays(10)), config, now);

        // Labels use the same formatter as SM-2: < 30 days show "Nd", longer
        // gaps roll up to months (33d → 1mo, 79d → 3mo).
        assertEquals("10m", preview.getAgain()); // relearning step
        assertEquals("15d", preview.getHard());
        assertEquals("1mo", preview.getGood());  // 33 days
        assertEquals("3mo", preview.getEasy());  // 79 days
    }
}
